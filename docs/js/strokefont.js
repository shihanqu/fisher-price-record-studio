function segmentPoly([x1, y1], [x2, y2], w) {
  const dx = x2 - x1, dy = y2 - y1;
  const L = Math.hypot(dx, dy) || 1;
  const nx = (-dy / L) * w / 2, ny = (dx / L) * w / 2;
  const ex = (dx / L) * w / 2, ey = (dy / L) * w / 2;          // extend the ends so joints close
  const poly = [[x1 + nx - ex, y1 + ny - ey], [x2 + nx + ex, y2 + ny + ey], [x2 - nx + ex, y2 - ny + ey], [x1 - nx - ex, y1 - ny - ey]];
  let area = 0;
  for (let i = 0; i < 4; i++) area += poly[i][0] * poly[(i + 1) % 4][1] - poly[(i + 1) % 4][0] * poly[i][1];
  return area > 0 ? poly : poly.reverse();                     // counter-clockwise = solid
}

/** Polygons ([[x, y], ...]) for `text` with cap height `size`, centred on x = 0. */
export function textPolygons(text, size, stroke, centre = true) {
  const s = size / 6, adv = 5.5 * s;
  const polys = [];
  let x = 0;
  for (const ch of text.toUpperCase()) {
    for (const line of GLYPHS[ch] || []) {
      const pts = line.map(([px, py]) => [x + px * s, py * s]);
      for (let i = 0; i + 1 < pts.length; i++) polys.push(segmentPoly(pts[i], pts[i + 1], stroke));
    }
    x += adv;
  }
  if (centre && x) {
    const off = (x - adv + 4 * s) / 2;
    return polys.map((poly) => poly.map(([px, py]) => [px - off, py]));
  }
  return polys;
}
