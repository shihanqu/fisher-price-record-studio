def _segment_poly(p, q, w):
    (x1, y1), (x2, y2) = p, q
    dx, dy = x2 - x1, y2 - y1
    L = math.hypot(dx, dy) or 1.0
    nx, ny = -dy / L * w / 2, dx / L * w / 2
    ex, ey = dx / L * w / 2, dy / L * w / 2      # extend ends so joints close
    poly = [(x1 + nx - ex, y1 + ny - ey), (x2 + nx + ex, y2 + ny + ey),
            (x2 - nx + ex, y2 - ny + ey), (x1 - nx - ex, y1 - ny - ey)]
    # counter-clockwise so the CSG library treats it as solid, not a hole
    area = sum(poly[i][0] * poly[(i + 1) % 4][1] - poly[(i + 1) % 4][0] * poly[i][1] for i in range(4))
    return poly if area > 0 else poly[::-1]


def text_polygons(text: str, size: float, stroke: float, centre: bool = True):
    """Polygons (lists of (x,y)) for `text` with cap height `size`, centred on x=0."""
    s = size / 6.0
    adv = 5.5 * s
    polys = []
    x = 0.0
    for ch in text.upper():
        for stroke_pts in _G.get(ch, []):
            pts = [(x + px * s, py * s) for px, py in stroke_pts]
            for a, b in zip(pts, pts[1:]):
                polys.append(_segment_poly(a, b, stroke))
        x += adv
    if centre:
        off = (x - adv + 4 * s) / 2 if x else 0
        polys = [[(px - off, py) for px, py in poly] for poly in polys]
    return polys
